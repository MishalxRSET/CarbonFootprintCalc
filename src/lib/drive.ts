/**
 * Formats a Markdown document for the plan
 */
function generatePlanMarkdown(payload: PlanExportPayload): string {
  const dateFormatted = new Date().toLocaleDateString('en-IN', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  });

  return `# ${payload.planTitle}
**Generated Date:** ${dateFormatted}  
**Target Reduction:** -${payload.targetPercent}% over ${payload.horizonYears} Years  
**Standard:** GHG Protocol Corporate & Scope 3 Standards | CEA India Grid Baseline (0.716 kg CO₂e/kWh)

---

## 1. Executive Summary

| Metric | Value |
|---|---|
| **Baseline Carbon Footprint** | **${payload.baselineTonnes} tCO₂e / year** |
| **Annual Target Abatement** | **-${payload.abatedTonnes} tCO₂e / year** |
| **Projected Net Footprint** | **${payload.netRemainingTonnes} tCO₂e / year** |
| **Target Progress Achieved** | **${Math.min(100, Math.round((payload.abatedTonnes / (payload.baselineTonnes * (payload.targetPercent / 100))) * 100))}%** |
| **Est. Annual Operating Savings** | **₹${payload.annualSavingsINR.toLocaleString('en-IN')} / year** |

---

## 2. Selected Decarbonization Interventions (${payload.selectedStrategies.length})

${payload.selectedStrategies
  .map(
    (s, idx) => `### ${idx + 1}. ${s.title}
- **Sector:** ${s.category}
- **Target GHG Scope:** ${s.targetScope || s.category}
- **Potential Abatement:** **${(s.potentialReductionKgCO2e / 1000).toFixed(2)} tCO₂e/yr** (${s.potentialReductionKgCO2e.toLocaleString()} kg/yr)
- **Cost Tier:** ${s.costEstimate}
- **Ease of Implementation:** ${s.implementationEase}
- **Description:** ${s.description}
- **Environmental Impact:** ${s.pros.environmental}
- **Financial/Economic Return:** ${s.pros.economic}
`
  )
  .join('\n')}

---

## 3. Emission Accounting Methodology
Emission modeling adheres to the Greenhouse Gas Protocol and Central Electricity Authority (Ministry of Power, Government of India).
- **Grid Power (Scope 2):** 0.716 kg CO₂e / kWh
- **Domestic Cooking Gas (Scope 1):** 42.4 kg CO₂e per 14.2 kg LPG cylinder
- **Motor Petrol (Scope 1):** 2.31 kg CO₂e / litre
- **Paris Agreement Benchmark:** 2.0 tCO₂e per capita ceiling
- **India National Benchmark:** 2.1 tCO₂e per capita baseline
`;
}

/**
 * Downloads the customized plan file directly to the client machine
 */
export function downloadPlanLocally(payload: PlanExportPayload, format: DrivePlanFormat = 'markdown'): void {
  const dateStamp = new Date().toISOString().split('T')[0];
  const cleanTitle = (payload.planTitle.trim() || 'Climate Action Plan 2026').replace(/[\\/:*?"<>|]/g, '-');
  let content = '';
  let filename = '';
  let mimeType = '';

  if (format === 'markdown') {
    content = generatePlanMarkdown(payload);
    filename = `${cleanTitle} - ${dateStamp}.md`;
    mimeType = 'text/markdown;charset=utf-8';
  } else if (format === 'json') {
    content = JSON.stringify(
      {
        planTitle: payload.planTitle,
        generatedDate: new Date().toISOString(),
        framework: 'GHG Protocol & CEA India (0.716 kg CO2/kWh)',
        summary: {
          baselineTonnesCO2e: payload.baselineTonnes,
          targetReductionPercent: payload.targetPercent,
          annualAbatementTonnesCO2e: payload.abatedTonnes,
          projectedNetTonnesCO2e: payload.netRemainingTonnes,
          annualEstimatedSavingsINR: payload.annualSavingsINR,
          timelineYears: payload.horizonYears,
        },
        selectedStrategies: payload.selectedStrategies,
      },
      null,
      2
    );
    filename = `${cleanTitle} - ${dateStamp}.json`;
    mimeType = 'application/json;charset=utf-8';
  } else {
    content = generatePlanHTML(payload);
    filename = `${cleanTitle} - ${dateStamp}.html`;
    mimeType = 'text/html;charset=utf-8';
  }

  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

