import { DriveFileItem, ReductionStrategy, CalculationResult } from '../types';

export interface PlanExportPayload {
  planTitle: string;
  baselineTonnes: number;
  targetPercent: number;
  abatedTonnes: number;
  netRemainingTonnes: number;
  annualSavingsINR: number;
  horizonYears: number;
  selectedStrategies: ReductionStrategy[];
}

export type DrivePlanFormat = 'gdoc' | 'markdown' | 'json';

/**
 * Turn a failed Drive API response into one of the app's error codes:
 * UNAUTHORIZED_EXPIRED_TOKEN (401), DRIVE_SCOPE_MISSING (Drive permission not granted),
 * DRIVE_API_DISABLED (Drive API off in the Google Cloud project), or the API's own message.
 */
export async function toDriveError(response: Response, fallback: string): Promise<Error> {
  if (response.status === 401) return new Error('UNAUTHORIZED_EXPIRED_TOKEN');
  const body = await response.json().catch(() => ({}));
  const err = (body as { error?: { message?: string; errors?: { reason?: string }[]; details?: { reason?: string }[] } })?.error ?? {};
  const reasons = [...(err.errors ?? []), ...(err.details ?? [])].map((e) => e?.reason).filter(Boolean);
  if (response.status === 403) {
    if (
      reasons.some((r) => r === 'insufficientPermissions' || r === 'ACCESS_TOKEN_SCOPE_INSUFFICIENT') ||
      /insufficient authentication scopes/i.test(err.message ?? '')
    ) {
      return new Error('DRIVE_SCOPE_MISSING');
    }
    if (reasons.some((r) => r === 'accessNotConfigured' || r === 'SERVICE_DISABLED')) {
      return new Error('DRIVE_API_DISABLED');
    }
  }
  return new Error(err.message || `${fallback} (${response.status})`);
}

/**
 * Saves the customized Climate Action Plan directly to the user's Google Drive.
 * Supports Google Docs (converted natively from HTML), Markdown (.md), and structured JSON.
 */
export async function savePlanToGoogleDrive(
  accessToken: string,
  payload: PlanExportPayload,
  format: DrivePlanFormat = 'gdoc'
): Promise<DriveFileItem> {
  const boundary = '-------ClimatePlanDriveBoundary' + Date.now();
  const delimiter = `\r\n--${boundary}\r\n`;
  const closeDelimiter = `\r\n--${boundary}--`;

  const dateStamp = new Date().toISOString().split('T')[0];
  const cleanTitle = (payload.planTitle.trim() || 'Climate Action Plan 2026').replace(/[\\/:*?"<>|]/g, '-');

  let fileName = `${cleanTitle}`;
  let targetMimeType = 'application/vnd.google-apps.document';
  let uploadContentType = 'text/html; charset=UTF-8';
  let fileContent = '';

  if (format === 'gdoc') {
    fileName = `${cleanTitle} (${dateStamp})`;
    targetMimeType = 'application/vnd.google-apps.document';
    uploadContentType = 'text/html; charset=UTF-8';
    fileContent = generatePlanHTML(payload);
  } else if (format === 'markdown') {
    fileName = `${cleanTitle} - ${dateStamp}.md`;
    targetMimeType = 'text/markdown';
    uploadContentType = 'text/markdown; charset=UTF-8';
    fileContent = generatePlanMarkdown(payload);
  } else if (format === 'json') {
    fileName = `${cleanTitle} - ${dateStamp}.json`;
    targetMimeType = 'application/json';
    uploadContentType = 'application/json; charset=UTF-8';
    fileContent = JSON.stringify(
      {
        planTitle: payload.planTitle,
        generatedDate: new Date().toISOString(),
        framework: 'GHG Protocol & CEA India (0.716 kg CO2/kWh)',
        summary: {
          baselineTonnesCO2e: payload.baselineTonnes,
          targetReductionPercent: payload.targetPercent,
          annualAbatementTonnesCO2e: payload.abatedTonnes,
          projectedNetTonnesCO2e: payload.netRemainingTonnes,
          annualEstimatedSavingsINR: payload.annualSavingsINR,
          timelineYears: payload.horizonYears,
        },
        selectedStrategies: payload.selectedStrategies.map((s) => ({
          id: s.id,
          title: s.title,
          category: s.category,
          targetScope: s.targetScope || 'Scope 1 & 2',
          potentialReductionKgCO2e: s.potentialReductionKgCO2e,
          potentialReductionTonnesCO2e: Number((s.potentialReductionKgCO2e / 1000).toFixed(2)),
          costEstimate: s.costEstimate,
          implementationEase: s.implementationEase,
          pros: s.pros,
        })),
      },
      null,
      2
    );
  }

  const metadata = {
    name: fileName,
    mimeType: targetMimeType,
    description: `Climate Action Decarbonization Plan generated by Carbon Accounting Platform. Target: -${payload.targetPercent}% (${payload.abatedTonnes} tCO2e/yr abatement).`,
  };

  const multipartRequestBody =
    delimiter +
    'Content-Type: application/json; charset=UTF-8\r\n\r\n' +
    JSON.stringify(metadata) +
    delimiter +
    `Content-Type: ${uploadContentType}\r\n\r\n` +
    fileContent +
    closeDelimiter;

  const response = await fetch(
    'https://www.googleapis.com/upload/drive/v3/files?uploadType=multipart&fields=id,name,mimeType,webViewLink,createdTime,modifiedTime,size,iconLink',
    {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${accessToken}`,
        'Content-Type': `multipart/related; boundary=${boundary}`,
      },
      body: multipartRequestBody,
    }
  );

  if (!response.ok) {
    throw await toDriveError(response, 'Google Drive upload error');
  }

  const savedFile: DriveFileItem = await response.json();
  return savedFile;
}

/**
 * List files in user's Drive created by or matching the Climate Action Plan
 */
export async function listSavedPlansFromDrive(accessToken: string): Promise<DriveFileItem[]> {
  try {
    const query = encodeURIComponent(
      `trashed = false and (name contains 'Climate' or name contains 'Carbon' or name contains 'Plan' or name contains 'Decarbonization')`
    );
    const fields = encodeURIComponent(
      'files(id, name, mimeType, modifiedTime, createdTime, size, webViewLink, iconLink, thumbnailLink, description)'
    );
    const url = `https://www.googleapis.com/drive/v3/files?q=${query}&fields=${fields}&pageSize=15&orderBy=createdTime desc`;

    const response = await fetch(url, {
      headers: {
        Authorization: `Bearer ${accessToken}`,
        Accept: 'application/json',
      },
    });

    if (!response.ok) {
      throw await toDriveError(response, 'Drive list error');
    }

    const data = await response.json();
    return data.files || [];
  } catch (error) {
    console.error('Error listing plans from Google Drive:', error);
    throw error;
  }
}

